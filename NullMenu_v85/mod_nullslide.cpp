// ---------------------------------------------------------------- 写真を読む
// 写真 fi を spr[k] に読む(写真がなければ黒)
static bool loadPhoto(int fi, int k) {
  if (sprFile[k] == fi && fi >= 0) return sprOk[k];
  sprFile[k] = fi; sprOk[k] = false;
  spr[k]->fillSprite(TFT_BLACK);
  if (fi < 0 || fi >= nFiles) return false;
  char path[64]; snprintf(path, sizeof(path), "/slide/%s", names[fi]);
  File f = FFat.open(path, "r");
  if (!f) return false;
  const size_t n = f.size();
  if (n == 0 || n > (size_t)MAX_JPG) { f.close(); return false; }
  const size_t got = f.read(jpgBuf, n);
  f.close();
  int w = 0, h = 0;
  if (got != n || !jpgSize(jpgBuf, n, &w, &h)) { Serial.printf("# cannot read %s\n", names[fi]); return false; }
  float sc = 1.0f;                                // 画面より大きいときだけ縮める(ふつうはページが画面の大きさにしてある)
  if (w > S || h > S) sc = fminf((float)S / w, (float)S / h);
  const int dw = (int)(w * sc), dh = (int)(h * sc);
  const uint32_t t0 = millis();
  sprOk[k] = spr[k]->drawJpg(jpgBuf, (uint32_t)n, (S - dw) / 2, (S - dh) / 2, 0, 0, 0, 0, sc, sc);
  if (cfgFlip) {                                  // さかさま: 並びを逆にすると 180 度回る
    uint16_t* p = img[k];
    for (size_t i = 0, j = (size_t)S * S - 1; i < j; ++i, --j) { const uint16_t t = p[i]; p[i] = p[j]; p[j] = t; }
  }
  Serial.printf("# photo %s  %dx%d  %u ms%s\n", names[fi], w, h, (unsigned)(millis() - t0), sprOk[k] ? "" : "  (failed)");
  return sprOk[k];
}

