static void webUpload() {
  HTTPRaw& r = web->raw();
  if (r.status == RAW_START) {
    webTouch();
    upErr = nullptr; upGot = 0; upShownMs = 0;
    upSize = (uint32_t)web->clientContentLength();
    String nm = web->header("X-Name");
    strncpy(upName, nm.c_str(), GNAME_MAX); upName[GNAME_MAX] = 0;
    if (rxActive) upErr = "BUSY";
    else if (!goodName(nm.c_str()) || nm.length() > GNAME_MAX) upErr = "NAME";
    else if (!fsOk) upErr = "NOFS";
    else if (upSize == 0 || upSize > (uint32_t)MAX_JPG) upErr = "BIG";
    else {
      fsStats();
      const int idx = findFile(upName);
      const size_t freeNow = (fsTotal > fsUsed ? fsTotal - fsUsed : 0) + (idx >= 0 ? sizes[idx] : 0);
      if ((size_t)upSize + 32768 > freeNow) upErr = "FULL";
      else if (idx < 0 && nFiles >= MAX_FILES) upErr = "MANY";
    }
    if (!upErr) {
      FFat.remove("/slide/~web.tmp");
      File f = FFat.open("/slide/~web.tmp", "w");
      if (!f) upErr = "OPEN"; else upFile = new File(f);
    }
    if (!upErr) drawProgress(upName, 0, upSize);
  } else if (r.status == RAW_WRITE) {
    if (upFile && !upErr && r.currentSize) {
      if (upFile->write(r.buf, r.currentSize) != r.currentSize) upErr = "SAVE";
      upGot += r.currentSize;
      if (millis() - upShownMs > 250) { upShownMs = millis(); drawProgress(upName, upGot, upSize); }
    }
  } else if (r.status == RAW_END) {
    webTouch();
    if (upErr || !upFile) { upClose(false); if (!upErr) upErr = "OPEN"; return; }
    upClose(true);
    if (upGot != upSize) { upErr = "SAVE"; FFat.remove("/slide/~web.tmp"); return; }
    char path[64]; snprintf(path, sizeof(path), "/slide/%s", upName);
    FFat.remove(path);
    if (!FFat.rename("/slide/~web.tmp", path)) { FFat.remove("/slide/~web.tmp"); upErr = "SAVE"; return; }
    char keep[GNAME_MAX + 1] = {0};
    if (pos >= 0 && pos < nFiles) strcpy(keep, names[order[pos]]);
    scanFiles();
    filesChanged(keep[0] ? keep : upName);
    snprintf(wifiMsg, sizeof(wifiMsg), "受け取りました(写真 %d 枚)", nFiles);
    Serial.printf("# wifi got %s  %u bytes\n", upName, (unsigned)upGot);
  } else {                                        // とちゅうで切れた
    upClose(false);
    upErr = "ABORT";
  }
}
