static void handleLine(char* s) {
  if (strncmp(s, "NMS ", 4)) return;
  char* cmd = s + 4;
  if (!strcmp(cmd, "HELLO")) {
    fsStats();
    char o[96]; snprintf(o, sizeof(o), "NMS HELLO 1 %u %u %d %d %d %d %d", (unsigned)fsTotal, (unsigned)fsUsed, nFiles, fsOk ? 1 : 0, S, nextSeq, roundScr ? 1 : 0); reply(o);
    sendCfg();
  } else if (!strcmp(cmd, "LIST")) {
    char o[96];
    for (int i = 0; i < nFiles; ++i) { snprintf(o, sizeof(o), "NMS FILE %u %s", (unsigned)sizes[i], names[i]); reply(o); }
    snprintf(o, sizeof(o), "NMS END %d", nFiles); reply(o);
  } else if (!strcmp(cmd, "CFG")) {
    sendCfg();
  } else if (!strncmp(cmd, "SET ", 4)) {
    int a, b, c, d, e;
    if (sscanf(cmd + 4, "%d %d %d %d %d", &a, &b, &c, &d, &e) != 5 || apiSet(a, b, c, d, e)) { reply("NMS ERR ARG"); return; }
  } else if (!strncmp(cmd, "PUT ", 4)) {
    unsigned sz = 0; char nm[64] = {0};
    if (sscanf(cmd + 4, "%u %63s", &sz, nm) != 2 || !goodName(nm)) { reply("NMS ERR NAME"); return; }
    if (!fsOk) { reply("NMS ERR NOFS"); return; }
    if (upFile) { reply("NMS ERR BUSY"); return; }   // Wi-Fi で受け取っている最中
    fsStats();
    const int idx = findFile(nm);
    const size_t freeNow = (fsTotal > fsUsed ? fsTotal - fsUsed : 0) + (idx >= 0 ? sizes[idx] : 0);
    if (sz == 0 || sz > (unsigned)MAX_JPG) { reply("NMS ERR BIG"); return; }
    if ((size_t)sz + 32768 > freeNow) { reply("NMS ERR FULL"); return; }
    if (idx < 0 && nFiles >= MAX_FILES) { reply("NMS ERR MANY"); return; }
    FFat.remove("/slide/~up.tmp");
    File f = FFat.open("/slide/~up.tmp", "w");
    if (!f) { reply("NMS ERR OPEN"); return; }
    rxFile = new File(f);
    strcpy(rxName, nm); rxSize = sz; rxGot = 0; rxSinceAck = 0; rxCrc = 0; rxLast = millis();
    rxActive = true; rxWaitDone = false; rxShownPct = -1;
    if (mode == M_TRANS) { ci = 1 - ci; pos = trTo; }
    showProgress(true);
    char o[32]; snprintf(o, sizeof(o), "NMS READY %d", CHUNK); reply(o);
  } else if (!strncmp(cmd, "DONE ", 5)) {
    if (!rxWaitDone) { reply("NMS ERR STATE"); return; }
    const uint32_t want = (uint32_t)strtoul(cmd + 5, nullptr, 16);
    rxFile->close(); delete rxFile; rxFile = nullptr;
    rxActive = rxWaitDone = false;
    if (want != rxCrc) { FFat.remove("/slide/~up.tmp"); reply("NMS ERR CRC"); backToShow(); return; }
    char path[64]; snprintf(path, sizeof(path), "/slide/%s", rxName);
    FFat.remove(path);
    if (!FFat.rename("/slide/~up.tmp", path)) { FFat.remove("/slide/~up.tmp"); reply("NMS ERR SAVE"); backToShow(); return; }
    scanFiles();
    filesChanged(rxName);                          // 受け取った写真を見せる
    replyOK();
    showNow(pos);
  } else if (!strncmp(cmd, "DEL ", 4)) {
    if (apiDel(cmd + 4)) { reply("NMS ERR NOFILE"); return; }
    replyOK();
  } else if (!strcmp(cmd, "CLEAR")) {               // 全部消す
    apiClear();
    replyOK();
  } else if (!strncmp(cmd, "SHOW ", 5)) {
    if (apiShow(cmd + 5)) { reply("NMS ERR NOFILE"); return; }
    replyOK();
  } else {
    reply("NMS ERR CMD");
  }
}

static void pollUsb() {
  for (int guard = 0; guard < 64; ++guard) {
    int av = Serial.available();
    if (av <= 0) break;
    if (rxActive && !rxWaitDone) {                 // データを受け取っている最中
      const uint32_t want = min((uint32_t)min(av, CHUNK), rxSize - rxGot);
      const int n = (int)Serial.read(rxBuf, want);
      if (n <= 0) break;
      rxFile->write(rxBuf, n);
      rxCrc = crcAdd(rxCrc, rxBuf, n);
      rxGot += n; rxSinceAck += n; rxLast = millis();
      if (rxSinceAck >= (uint32_t)CHUNK || rxGot >= rxSize) {
        rxSinceAck = 0;
        char o[32]; snprintf(o, sizeof(o), "NMS ACK %u", (unsigned)rxGot); reply(o);
      }
      if (rxGot >= rxSize) rxWaitDone = true;
      showProgress(rxGot >= rxSize);
      continue;
    }
    const int c = Serial.read();
    if (c < 0) break;
    if (c == '\r') continue;
    if (c == '\n') { line[lineLen] = 0; handleLine(line); lineLen = 0; continue; }
    if (lineLen < (int)sizeof(line) - 1) line[lineLen++] = (char)c;
  }
  if (rxActive && millis() - rxLast > 8000) rxAbort("TIMEOUT");
}

