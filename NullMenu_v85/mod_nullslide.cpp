void loop() {
  static uint32_t lastTapMs = 0;
  M5.update();
  pollUsb();
  if (rxActive) { delay(1); return; }             // 受け取っているあいだは、ほかのことは休む

  auto t = M5.Touch.getDetail();
  if (mode == M_WIFI) { wifiLoop(t.wasPressed() && !(t.x < 56 && t.y < 56)); return; }
  // ---- 消すかどうか / USB の説明
  if (mode == M_CONFIRM || mode == M_USBINFO) {
    int act = 0;                                   // 1 = 消す / -1 = もどる
    if (roundScr) {
      if (mode == M_CONFIRM && M5.BtnB.wasClicked()) act = 1;
      else if (M5.BtnA.wasClicked() || M5.BtnA.wasHold() || M5.BtnB.wasClicked()) act = -1;
    } else {
      if (M5.BtnPWR.wasClicked()) act = -1;
      if (t.wasPressed() && millis() - lastTapMs > 200 && !(t.x < 56 && t.y < 56)) {
        lastTapMs = millis();
        act = (mode == M_CONFIRM && t.x >= W / 2) ? 1 : -1;
      }
    }
    if (!act && millis() - confirmT > (uint32_t)MENU_IDLE_MS * 2) act = -1;
    if (act == 1) { doDelete(); return; }
    if (act == -1) { mode = M_MENU; menuT = millis(); drawMenu(); return; }
    delay(5);
    return;
  }
  // ---- 設定の画面
  if (mode == M_MENU) {
    if (roundScr) {
      if (M5.BtnA.wasHold())         { closeMenu(); return; }
      if (M5.BtnA.wasClicked())      { menuSel = (menuSel + 1) % MENU_N; menuT = millis(); drawMenu(); }
      if (M5.BtnB.wasClicked())      { menuT = millis(); menuChange(menuSel); return; }
    } else {
      if (M5.BtnPWR.wasClicked())    { closeMenu(); return; }
      if (t.wasPressed() && millis() - lastTapMs > 200 && !(t.x < 56 && t.y < 56)) {
        lastTapMs = millis(); menuT = millis();
        const int rh = menuRowH(), yy = t.y - YOFF;
        const int i = (int)floorf((yy - (menuY0() - rh / 2)) / (float)rh);
        if (i >= 0 && i < MENU_N) { menuSel = i; menuChange(i); return; }
      }
    }
    if (millis() - menuT > (uint32_t)MENU_IDLE_MS) closeMenu();
    delay(5);
    return;
  }

  // ---- ボタン
  int go = 0;
  if (roundScr) {
    if (M5.BtnA.wasHold())         go = -1;
    else if (M5.BtnA.wasClicked()) go = 1;
    if (M5.BtnB.wasClicked() && fsOk) { if (mode == M_TRANS) { ci = 1 - ci; pos = trTo; } openMenu(); return; }
  } else {
    if (M5.BtnPWR.wasClicked() && fsOk) { if (mode == M_TRANS) { ci = 1 - ci; pos = trTo; } openMenu(); return; }
    if (t.wasPressed() && millis() - lastTapMs > 250 && !(t.x < 56 && t.y < 56)) {
      lastTapMs = millis();
      go = t.x < W / 2 ? -1 : 1;
    }
  }

  if (mode == M_EMPTY) { delay(10); return; }
  if (mode == M_TRANS) {
    if (go) { ci = 1 - ci; pos = trTo; mode = M_SHOW; goTo(pos + go, go, true); return; }   // 切り替え中に押した: すぐ次へ
    stepTrans();
    return;
  }
  // M_SHOW
  if (go) { goTo(pos + go, go, true); return; }
  if (infoOn && (int32_t)(millis() - infoUntil) >= 0) { infoOn = false; present(K_IMG); }
  const uint32_t sec = SEC_VAL[cfgSec];
  if (sec && nFiles > 1 && millis() - shownAt >= sec * 1000u) { goTo(pos + 1, 1, false); return; }
  // ひまなときに、次の写真を読んでおく
  if (nFiles > 1 && millis() - shownAt > 150) {
    const int np = wrapPos(pos + 1);
    if (!(cfgOrd == 1 && np == 0)) loadPhoto(order[np], 1 - ci);   // ランダムで一回りするときは、混ぜ直してから読む
  }
  delay(5);
}


