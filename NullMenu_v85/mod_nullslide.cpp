// NullSlide v7  -  丸い画面で写真のスライドショー。写真は本体の Wi-Fi か USB ケーブルで送る
//   M5Stack StopWatch 用(丸い 466x466 画面)。CoreS3 系でも動きます(書き込むときに FATFS のある Partition Scheme を選ぶ)。
//
// 画面の中:
//   ・本体にしまってある写真(JPEG)を、決めた時間ごとに切り替えて見せます
//   ・切り替え方(パッと / ふわっとフェード / 横にスライド / ハートになって消える)、1枚の時間、順番(送った順 / ランダム)、
//     形(そのまま / ハート)、ハートの色(ハートのまわりと、切り替えのハートのふち)、向き、明るさを選べます。本体のボタンでも、送るページ(docs/slide.html)からでも変えられます
//   ・写真を切り替えたとき、下に「何枚目か」が少しのあいだ出ます
//
// 操作:
//   StopWatch … ボタンA 短押し: 次の写真   ボタンA 長押し: 前の写真   ボタンB 短押し: 設定
//               設定の中: ボタンA 短押し: 次の項目   ボタンB 短押し: 変える   ボタンA 長押し: とじる
//               「この写真を消す」: ボタンB: 消す   ボタンA: やめる
//               Wi-Fi の画面: ボタンA: QR コードを切り替え   ボタンB: Wi-Fi を切って戻る
//   CoreS3系  … 画面の右半分をタップ: 次の写真   左半分: 前の写真   電源ボタン短押し: 設定
//               設定の中: 項目をタップ: 変える   電源ボタン短押し・「とじる」: とじる
//               「この写真を消す」: 右半分をタップ: 消す   左半分・電源ボタン: やめる
//               Wi-Fi の画面: タップ: QR コードを切り替え   電源ボタン: Wi-Fi を切って戻る
//
// 写真の送り方(Wi-Fi):
//   1. ボタン B で設定を開いて「Wi-Fi で受け取る」を選ぶ(CoreS3 は電源ボタンで設定を開いて、タップ)
//   2. 画面の QR コードをスマホのカメラで読む → 本体の Wi-Fi「Null2-xxxx」に入る(パスワードは画面に出ている8けた)
//   3. A を押すと、ページの QR コードに変わる → 読む(または http://192.168.4.1 を開く)→ 写真を選ぶ
//   Wi-Fi に入ると、スマホは「インターネットなし」と出ますが、そのままで大丈夫です。ページが開かないときは、
//   スマホのモバイルデータ通信をいったん切ってみてください。終わったら B(CoreS3 は電源ボタン)で Wi-Fi を切ります。
//
// 写真の送り方(USB):
//   1. この作品を動かしたまま、USB ケーブルで PC につなぐ
//   2. PC の Chrome か Edge で「写真を送るページ」を開く
//      (GitHub の …/docs/slide.html。zip の中の docs/slide.html をダブルクリックで開いても使えます)
//   3. 「本体につなぐ」→ 出てきた一覧から StopWatch を選ぶ → 写真をページに落とす
//   ページが写真を画面の大きさに縮めて(「画面いっぱい」か「全体を入れる」を選べます)、JPEG にしてから送ります。
//   1枚 30〜80KB くらいなので、数百枚入ります(容量は GIF と共用)。いらない写真はページから消せます。
//   (Arduino IDE のシリアルモニタを開いていると、ページからつなげません。閉じてからつないでください)
//
// しまう場所:
//   書き込むときの Partition Scheme「16M Flash (3MB APP/9.9MB FATFS)」の、9.9MB の FATFS の区画の /slide に入れます。
//   設定は /slide.cfg に入れます。プログラムとは別の場所なので、写真を出し入れしてもプログラムは消えません。
//
// 必要なもの:
//   ボードマネージャー M5Stack >= 3.3.7 / ボード: M5StopWatch(CoreS3 なら M5CoreS3)
//     ツール: Partition Scheme「16M Flash (3MB APP/9.9MB FATFS)」、USB CDC On Boot「Enabled」
//   ライブラリ M5Unified >= 0.2.15, M5GFX >= 0.2.21(JPEG を読むのは M5GFX の drawJpg)
//
// しくみ:
//   写真は2枚ぶんの置き場(PSRAM)に読んでおきます。いま見せている1枚と、次の1枚です。
//   切り替えるときは、2枚を混ぜたり(フェード)ずらしたり(スライド)しながら、16 行ずつの帯にして画面へ送ります。
//   「形」は、写真の上にかぶせる窓の形です(写真そのものは変わりません)。
//   USB の送り受けは NullGif と同じしくみ(「NMS …」で始まる1行の約束ごとと、2KB ずつのデータ)です。



