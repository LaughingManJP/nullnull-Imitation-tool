static void shuffleOrder() {
  for (int i = 0; i < nFiles; ++i) order[i] = (uint16_t)i;
  if (cfgOrd == 1)
    for (int i = nFiles - 1; i > 0; --i) { int j = (int)(esp_random() % (uint32_t)(i + 1)); uint16_t t = order[i]; order[i] = order[j]; order[j] = t; }
}
static void scanFiles() {
  nFiles = 0; nextSeq = 1;
  if (!fsOk) return;
  File dir = FFat.open("/slide");
  if (!dir || !dir.isDirectory()) return;
  for (File f = dir.openNextFile(); f && nFiles < MAX_FILES; f = dir.openNextFile()) {
    if (f.isDirectory()) continue;
    const char* nm = f.name();
    const char* slash = strrchr(nm, '/');
    if (slash) nm = slash + 1;
    if (!goodName(nm)) continue;
    strncpy(names[nFiles], nm, GNAME_MAX); names[nFiles][GNAME_MAX] = 0;
    sizes[nFiles] = (uint32_t)f.size();
    const int sq = atoi(nm);                      // 頭の数字(ページが「送った順」の番号をつけて送る)
    if (sq >= nextSeq) nextSeq = sq + 1;
    ++nFiles;
  }
  // 名前の順(= 送った順)に並べる
  for (int i = 1; i < nFiles; ++i)
    for (int j = i; j > 0 && strcmp(names[j - 1], names[j]) > 0; --j) {
      char t[GNAME_MAX + 1]; strcpy(t, names[j]); strcpy(names[j], names[j - 1]); strcpy(names[j - 1], t);
      uint32_t z = sizes[j]; sizes[j] = sizes[j - 1]; sizes[j - 1] = z;
    }
  fsStats();
}
static int findFile(const char* nm) {
  for (int i = 0; i < nFiles; ++i) if (!strcmp(names[i], nm)) return i;
  return -1;
}
static int posOfFile(int fi) {
  for (int i = 0; i < nFiles; ++i) if (order[i] == fi) return i;
  return 0;
}
// 写真の一覧が変わった: 番号がずれるので、読んである写真は忘れる。見せていた写真は名前で探し直す
static void filesChanged(const char* keep) {
  sprFile[0] = sprFile[1] = -1;
  shuffleOrder();
  const int fi = keep && keep[0] ? findFile(keep) : -1;
  pos = fi >= 0 ? posOfFile(fi) : (nFiles ? 0 : -1);
}

// ---------------------------------------------------------------- 窓の形
// 行 y の区間を決める(ハートは (x²+y²-1)³ - x²y³ <= 0 の形)
static void buildMasks() {
  const float c = (S - 1) * 0.5f, rr = S * 0.5f + 1.0f;
  for (int y = 0; y < S; ++y) {                   // [0] 画面: 丸い画面はまる、四角い画面は四角いっぱい
    int16_t a0 = 0, a1 = S - 1;
    if (roundScr) {
      const float dy = y - c, w = rr * rr - dy * dy;
      if (w <= 0) { a0 = 1; a1 = 0; }
      else { const float s = sqrtf(w); a0 = (int16_t)max(0, (int)floorf(c - s)); a1 = (int16_t)min(S - 1, (int)ceilf(c + s)); }
    }
    mk[0][0][y] = a0; mk[0][1][y] = a1; mk[0][2][y] = 1; mk[0][3][y] = 0;
  }
  // ハート: 丸い画面では、まるの中にいちばん大きく入るように。四角い画面では、正方形にいちばん大きく
  const float k  = roundScr ? (S * 0.5f - 5.0f) / 1.25f : (S - 8.0f) / 2.28f;   // 1 あたりの点の数
  const float vc = roundScr ? 0.25f : 0.118f;                                   // 画面のまん中が、ハートのどの高さか
  for (int y = 0; y < S; ++y) {
    const float v = (S * 0.5f - (y + 0.5f)) / k + vc;
    int runs[2][2]; int nr = 0; bool in = false; int st = 0;
    for (int x = 0; x <= S; ++x) {
      bool h = false;
      if (x < S) {
        const float u = (x + 0.5f - S * 0.5f) / k;
        const float q = u * u + v * v - 1.0f;
        h = q * q * q - u * u * v * v * v <= 0.0f;
        if (h && !(mk[0][0][y] <= x && x <= mk[0][1][y])) h = false;
      }
      if (h && !in) { in = true; st = x; }
      if (!h && in) { in = false; if (nr < 2) { runs[nr][0] = st; runs[nr][1] = x - 1; ++nr; } }
    }
    mk[1][0][y] = nr > 0 ? runs[0][0] : 1; mk[1][1][y] = nr > 0 ? runs[0][1] : 0;
    mk[1][2][y] = nr > 1 ? runs[1][0] : 1; mk[1][3][y] = nr > 1 ? runs[1][1] : 0;
  }
  if (cfgFlip) {                                  // さかさま: ハートの窓も上下を逆に
    for (int k = 0; k < 4; ++k) for (int y = 0, j = S - 1; y < j; ++y, --j) { const int16_t t = mk[1][k][y]; mk[1][k][y] = mk[1][k][j]; mk[1][k][j] = t; }
  }
  // 帯ごとの左右(StopWatch の画面へ直接送るときは、x と幅が偶数でないと描かれない)
  for (int m = 0; m < 1; ++m)                     // (ハートのぶんは使わないので、画面のぶんだけ)
    for (int b = 0; b < NB; ++b) {
      int x0 = S, x1 = -1;
      for (int y = b * BAND; y < min(S, (b + 1) * BAND); ++y) {
        if (mk[m][0][y] <= mk[m][1][y]) { x0 = min(x0, (int)mk[m][0][y]); x1 = max(x1, (int)mk[m][1][y]); }
        if (mk[m][2][y] <= mk[m][3][y]) { x0 = min(x0, (int)mk[m][2][y]); x1 = max(x1, (int)mk[m][3][y]); }
      }
      if (x1 < x0) { mkBx[m][b] = 0; mkBw[m][b] = 0; continue; }
      x0 &= ~1; x1 |= 1; if (x1 > S - 1) x1 = S - 1;
      mkBx[m][b] = (int16_t)x0; mkBw[m][b] = (int16_t)((x1 - x0 + 1) & ~1);
    }
}

// ハートの形の表(切り替えの「ハート」で、大きさを変えながら使う)
static void buildHeartTab() {
  for (int i = 0; i < HN; ++i) {
    const float v = HV0 + (i + 0.5f) * (HV1 - HV0) / HN;
    float r[4] = {1, 0, 1, 0}; int nr = 0; bool in = false; float st = 0;
    const int NU = 1200;
    for (int j = 0; j <= NU; ++j) {
      const float u = -1.3f + j * (2.6f / NU);
      bool h = false;
      if (j < NU) { const float q = u * u + v * v - 1.0f; h = q * q * q - u * u * v * v * v <= 0.0f; }
      if (h && !in) { in = true; st = u; }
      if (!h && in) { in = false; if (nr < 2) { r[nr * 2] = st; r[nr * 2 + 1] = u; ++nr; } }
    }
    for (int k = 0; k < 4; ++k) hTab[i * 4 + k] = r[k];
  }
}

// ---------------------------------------------------------------- 画面へ
// 2つの色(バイトを入れ替えた 565)を a/32 で混ぜる
static inline uint16_t mix565(uint16_t p, uint16_t q, uint32_t a) {
  uint32_t x = __builtin_bswap16(p), y = __builtin_bswap16(q);
  x = (x | (x << 16)) & 0x07E0F81Fu;
  y = (y | (y << 16)) & 0x07E0F81Fu;
  uint32_t r = ((x * (32 - a) + y * a) >> 5) & 0x07E0F81Fu;
  return __builtin_bswap16((uint16_t)(r | (r >> 16)));
}

enum { K_IMG = 0, K_FADE = 1, K_SLIDE = 2, K_UI = 3, K_HEART = 4 };
static constexpr size_t nmOa50 = nmAlignTo(nmOv50, alignof(uint16_t)), nmOv51 = nmOa50 + sizeof(uint16_t); static uint16_t& hcolPix = *reinterpret_cast<uint16_t*>(NM_ARENA + nmOa50);  // ハートの色(画面へ送る形)
// 1行 [s, e] を作る(out は x = bx の位置から)
static inline void spanRow(uint16_t* out, int bx, int y, int s, int e, int kind, int prm, int dir) {
  if (s > e) return;
  const uint16_t* A = (kind == K_UI ? (const uint16_t*)ui->getBuffer() : img[ci]) + (size_t)y * S;
  uint16_t* o = out + (s - bx);
  const int n = e - s + 1;
  if (kind == K_IMG || kind == K_UI) { memcpy(o, A + s, n * 2); return; }
  const uint16_t* B = img[1 - ci] + (size_t)y * S;
  if (kind == K_FADE) { for (int i = 0; i < n; ++i) o[i] = mix565(A[s + i], B[s + i], (uint32_t)prm); return; }
  if (kind == K_HEART) {                          // ハート: うしろは次の写真。いまの写真は、小さくなるハートの中だけに、だんだん薄く
    memcpy(o, B + s, n * 2);
    const float t = prm * (1.0f / 4096.0f);
    const float k = S * 1.15f * (1.0f - t) * (1.0f - t * 0.25f);   // 1 あたりの点の数(はじめは画面より大きい)
    const uint32_t full = (uint32_t)((1.0f - t * t) * 32.0f + 0.5f);
    if (k < 1.0f || full == 0) return;
    const int yy = cfgFlip ? S - 1 - y : y;      // さかさまのときは、ハートも上下を逆に
    const float cx = S * 0.5f, EDGE = 3.0f;
    if (cfgHcol != 0) {                          // ふちの色: 少し大きいハートを、選んだ色で先に塗る
      const float kr = k + 12.0f;
      const float vr = (S * 0.5f - (yy + 0.5f)) / kr + 0.18f;
      const int hr = (int)((vr - HV0) * (HN / (HV1 - HV0)));
      const uint32_t ar = (uint32_t)((1.0f - t * t) * 26.0f + 0.5f);
      if (hr >= 0 && hr < HN && ar) {
        const float* rr = hTab + hr * 4;
        for (int q = 0; q < 2; ++q) {
          if (rr[q * 2 + 1] <= rr[q * 2]) continue;
          const int x0 = max(s, (int)ceilf(cx + rr[q * 2] * kr - 0.5f)), x1 = min(e, (int)floorf(cx + rr[q * 2 + 1] * kr - 0.5f));
          for (int x = x0; x <= x1; ++x) o[x - s] = mix565(o[x - s], hcolPix, ar);
        }
      }
    }
    const float v = (S * 0.5f - (yy + 0.5f)) / k + 0.18f;
    const int hi = (int)((v - HV0) * (HN / (HV1 - HV0)));
    if (hi < 0 || hi >= HN) return;
    const float* r = hTab + hi * 4;
    for (int q = 0; q < 2; ++q) {
      if (r[q * 2 + 1] <= r[q * 2]) continue;
      const float xa = cx + r[q * 2] * k, xb = cx + r[q * 2 + 1] * k;   // この行の、ハートの左右
      const int x0 = max(s, (int)ceilf(xa - 0.5f)), x1 = min(e, (int)floorf(xb - 0.5f));
      for (int x = x0; x <= x1; ++x) {
        const float d = fminf(x + 0.5f - xa, xb - (x + 0.5f));
        const uint32_t a = d >= EDGE ? full : (uint32_t)(full * d * (1.0f / EDGE));   // ふちはぼかす
        if (d >= EDGE) o[x - s] = mix565(B[s + (x - s)], A[s + (x - s)], a);
        else if (a) o[x - s] = mix565(o[x - s], A[s + (x - s)], a);        // ふちは、ふちの色からなめらかに
      }
    }
    return;
  }
  // スライド: dir=1 なら、いまの写真が左へ出ていき、次の写真が右から入る
  for (int x = s; x <= e;) {
    int sx = dir > 0 ? x + prm : x - prm;
    const uint16_t* src; int lim;
    if (dir > 0) { if (sx < S) { src = A + sx; lim = S - sx; } else { src = B + (sx - S); lim = 2 * S - sx; } }
    else         { if (sx >= 0) { src = A + sx; lim = S - sx; } else { src = B + (sx + S); lim = -sx; } }
    const int k = min(e - x + 1, lim);
    memcpy(out + (x - bx), src, k * 2);
    x += k;
  }
}

// 画面ぜんぶを作って送る。kind: K_IMG(いまの写真) / K_FADE(prm = 0..32) / K_SLIDE(prm = ずらす点の数) / K_UI(文字の画面)
//   / K_HEART(prm = 0..4096 の進み)
static void present(int kind, int prm = 0, int dir = 1) {
  const int m = (kind == K_UI || cfgShape == 0) ? 0 : 1;
  hcolPix = __builtin_bswap16(rgb(HCOL_RGB[cfgHcol][0], HCOL_RGB[cfgHcol][1], HCOL_RGB[cfgHcol][2]));   // 帯の中は、バイトを入れかえた形
  const bool capOn = infoOn && kind != K_UI;
  if (!fbMode) M5.Display.startWrite();
  int slot = 0;
  for (int b = 0; b < NB; ++b) {
    const int y0 = b * BAND, h = min(BAND, S - y0);
    int bx = mkBx[0][b], bw = mkBw[0][b];          // 画面の中ぜんぶを送る(ハートの外は黒で塗る)
    const bool capRows = capOn && y0 < capY + CAPH && y0 + h > capY;
    if (capRows) { const int x1 = max(bx + bw, capX + CAPW); bx = min(bx, capX); bw = x1 - bx; }
    if (bw <= 0) continue;
    uint16_t* out = band[slot];
    for (int y = y0; y < y0 + h; ++y) {
      uint16_t* o = out + (y - y0) * bw;
      memset(o, 0, bw * 2);
      if (m == 1 && cfgHcol != 0) {               // ハートのまわりを、選んだ色で塗る
        const int a0 = max((int)mk[0][0][y], bx), a1 = min((int)mk[0][1][y], bx + bw - 1);
        for (int x = a0; x <= a1; ++x) o[x - bx] = hcolPix;
      }
      spanRow(o, bx, y, max((int)mk[m][0][y], bx), min((int)mk[m][1][y], bx + bw - 1), kind, prm, dir);
      spanRow(o, bx, y, max((int)mk[m][2][y], bx), min((int)mk[m][3][y], bx + bw - 1), kind, prm, dir);
      if (capRows && y >= capY && y < capY + CAPH)
        memcpy(o + (capX - bx), (const uint16_t*)cap->getBuffer() + (y - capY) * CAPW, CAPW * 2);
    }
    if (fbMode) M5.Display.pushImage(XOFF + bx, YOFF + y0, bw, h, out);
    else { M5.Display.waitDMA(); M5.Display.pushImageDMA(XOFF + bx, YOFF + y0, bw, h, out); }
    slot ^= 1;
  }
  if (!fbMode) { M5.Display.waitDMA(); M5.Display.endWrite(); }
}

