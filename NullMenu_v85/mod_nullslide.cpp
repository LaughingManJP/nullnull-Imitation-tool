// CRC32(PC から送られた写真が、途中で化けていないか確かめる)
static uint32_t crcAdd(uint32_t crc, const uint8_t* p, size_t n) {
  static const uint32_t T[16] = {
    0x00000000, 0x1DB71064, 0x3B6E20C8, 0x26D930AC, 0x76DC4190, 0x6B6B51F4, 0x4DB26158, 0x5005713C,
    0xEDB88320, 0xF00F9344, 0xD6D6A3E8, 0xCB61B38C, 0x9B64C2B0, 0x86D3D2D4, 0xA00AE278, 0xBDBDF21C };
  crc = ~crc;
  for (size_t i = 0; i < n; ++i) {
    crc ^= p[i];
    crc = (crc >> 4) ^ T[crc & 15];
    crc = (crc >> 4) ^ T[crc & 15];
  }
  return ~crc;
}

// 名前は英数字と . _ - だけ、.jpg で終わるもの
static bool goodName(const char* s) {
  int n = (int)strlen(s);
  if (n < 5 || n > GNAME_MAX) return false;
  for (int i = 0; i < n; ++i) {
    char c = s[i];
    if (!((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '.' || c == '_' || c == '-')) return false;
  }
  if (s[0] == '.' || s[0] == '~') return false;
  const char* e = s + n - 4;
  return (e[0] == '.') && (e[1] == 'j' || e[1] == 'J') && (e[2] == 'p' || e[2] == 'P') && (e[3] == 'g' || e[3] == 'G');
}

// JPEG の大きさを読む。TJpgDec が読めない形(プログレッシブなど)なら false
static bool jpgSize(const uint8_t* p, size_t n, int* w, int* h) {
  if (n < 4 || p[0] != 0xFF || p[1] != 0xD8) return false;
  size_t i = 2;
  while (i + 9 < n) {
    if (p[i] != 0xFF) { ++i; continue; }
    const uint8_t m = p[i + 1];
    if (m == 0xFF) { ++i; continue; }
    if (m == 0xD8 || m == 0x01 || (m >= 0xD0 && m <= 0xD7)) { i += 2; continue; }
    const size_t len = ((size_t)p[i + 2] << 8) | p[i + 3];
    if (m >= 0xC0 && m <= 0xCF && m != 0xC4 && m != 0xC8 && m != 0xCC) {
      *h = (p[i + 5] << 8) | p[i + 6]; *w = (p[i + 7] << 8) | p[i + 8];
      return (m == 0xC0 || m == 0xC1) && *w > 0 && *h > 0;
    }
    i += 2 + len;
  }
  return false;
}

