static void stepTrans() {
  const uint32_t dur = trKind == 1 ? FADE_MS : trKind == 3 ? HEART_MS : SLIDE_MS;
  const uint32_t el = millis() - trT0;
  if (el >= dur) {
    ci = 1 - ci; pos = trTo;
    if (trInfo) setInfo();
    present(K_IMG);
    mode = M_SHOW; shownAt = millis();
    return;
  }
  float t = el / (float)dur;
  t = t * t * (3.0f - 2.0f * t);                  // はじめと終わりをゆっくり
  if (trKind == 1) present(K_FADE, (int)(t * 32.0f + 0.5f));
  else if (trKind == 3) present(K_HEART, (int)(t * 4096.0f + 0.5f));
  else             present(K_SLIDE, (int)(t * S + 0.5f), trDir);
}

